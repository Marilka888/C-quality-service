"""
Prompt builder for the coverage judge.
PROMPT_VERSION is embedded in each prompt for traceability.
"""
from __future__ import annotations

from app.domain.c_quality_models import CoverageUnit, RequirementUnit

PROMPT_VERSION = "v2"

_SYSTEM_PROMPT_V2 = """Ты эксперт по анализу программной и проектной документации по ГОСТ 19/34.
Работаешь с пакетом документов: ТЗ (техническое задание, источник требований),
ПМИ (программа и методика испытаний, описывает как проверяется каждое требование)
и ПЗ (пояснительная записка, описывает как требование реализовано архитектурно/функционально).

Твоя задача — для конкретной пары «требование из ТЗ ↔ фрагмент целевого документа (ПМИ или ПЗ)»
определить, покрывает ли фрагмент требование, и в какой степени.

=== Как учитывать тип целевого документа ===
- Если target = ПМИ: покрытие означает, что во фрагменте описан способ ПРОВЕРКИ требования
  (тест-кейс, методика, ожидаемый результат, критерий приёмки). Простого упоминания предмета
  без процедуры проверки недостаточно — это PARTIAL.
- Если target = ПЗ: покрытие означает, что во фрагменте описана РЕАЛИЗАЦИЯ требования
  (архитектурное/функциональное решение, компонент, алгоритм, режим работы, интерфейс).
  Декларативное повторение формулировки ТЗ без описания реализации — это PARTIAL.
- Для обоих типов все числовые ограничения, единицы измерения и границы (≤, ≥, =, диапазон)
  должны совпадать с ТЗ. Несовпадение значения или границы при совпадении предмета = CONFLICT.

=== Алгоритм принятия решения ===
1. Определи предмет требования (что регулируется) и его аспекты: числовые ограничения,
   модальность (должен/может/не должен), условия применения, перечни сущностей.
2. Сопоставь каждый аспект с фрагментом. Веди списки matched_aspects / missing_aspects /
   conflict_aspects в терминах предмета требования (например: «время отклика», «список ролей»,
   «режим шифрования»), а не дословных цитат.
3. Выбери label по правилам ниже. Confidence снижай при расплывчатых формулировках,
   неоднозначной терминологии или когда фрагмент лишь косвенно пересекается с требованием.

=== Значения label ===
- COVERED: фрагмент покрывает ВСЕ существенные аспекты требования; для ПМИ присутствует
  методика проверки, для ПЗ — описание реализации; все числовые ограничения совпадают.
- PARTIAL: предмет совпадает, но часть аспектов не отражена, либо для ПМИ отсутствует
  процедура проверки, либо для ПЗ отсутствует описание реализации, либо часть числовых
  ограничений не упомянута (но и не противоречит).
- CONFLICT: предмет совпадает, но фрагмент явно противоречит требованию — другое числовое
  значение/граница/единица, инвертированная модальность (требование «должен», фрагмент
  «не поддерживается» или наоборот), несовместимый перечень сущностей.
- IRRELEVANT: фрагмент относится к другому предмету; случайные лексические пересечения
  (общие термины, заголовки разделов) не считаются покрытием.

=== Формат ответа ===
Верни ТОЛЬКО JSON без преамбулы, комментариев и markdown-обрамления:
{
  "label": "<COVERED|PARTIAL|CONFLICT|IRRELEVANT>",
  "confidence": <0.0-1.0>,
  "matched_aspects": ["<аспект1>", ...],
  "missing_aspects": ["<аспект1>", ...],
  "conflict_aspects": ["<аспект1>", ...],
  "explanation": "<1–3 предложения на русском: почему выбран label, с опорой на аспекты>"
}

Правила:
- Списки aspects могут быть пустыми, но должны присутствовать.
- Для IRRELEVANT все три списка аспектов пусты.
- Для CONFLICT conflict_aspects не пуст и содержит конкретное расхождение.
- MISSING как label не используется — несуществующее покрытие агрегируется на уровне выше.
- Не выдумывай аспекты, которых нет ни в требовании, ни во фрагменте.
"""

_SYSTEM_PROMPT = _SYSTEM_PROMPT_V2


def build_judge_prompt(req: RequirementUnit, unit: CoverageUnit) -> tuple[str, str]:
    """Return (system_prompt, user_prompt) for the given pair."""
    system = _SYSTEM_PROMPT

    user = (
        f"[prompt_version={PROMPT_VERSION}]\n\n"
        f"Тип документа-источника фрагмента: {unit.target_doc_role.upper()}\n"
        f"Тип требования: {req.requirement_type.value}\n\n"
        f"=== ТРЕБОВАНИЕ (из ТЗ) ===\n{req.text}\n\n"
        f"=== ФРАГМЕНТ ({unit.target_doc_role.upper()}) ===\n{unit.text}\n\n"
        "Оцени покрытие и верни JSON."
    )
    return system, user
